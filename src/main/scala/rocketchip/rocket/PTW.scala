/** PTE request from TLB to PTW
  *
  * TLB send a PTE request to PTW when L1TLB miss
  */
class PTWReq(implicit p: Parameters) extends CoreBundle()(p) {
  val addr = UInt(vpnBits bits)
  val need_gpa = Bool()
  val vstage1 = Bool()
  val stage2 = Bool()
}

/** chisel3.util.Valid(new PTWReq): the TLB->PTW request carries its own valid bit. */
class ValidPTWReq(implicit p: Parameters) extends CoreBundle()(p) {
  val valid = Bool()
  val bits = new PTWReq
}

/** PTE info from L2TLB to TLB */
class PTWResp(implicit p: Parameters) extends CoreBundle()(p) {
  /** ptw access exception */
  val ae_ptw = Bool()
  /** final access exception */
  val ae_final = Bool()
  /** page fault */
  val pf = Bool()
  /** guest page fault */
  val gf = Bool()
  /** hypervisor read */
  val hr = Bool()
  /** hypervisor write */
  val hw = Bool()
  /** hypervisor execute */
  val hx = Bool()
  /** PTE to refill L1TLB */
  val pte = new PTE
  /** pte pglevel */
  val level = UInt(log2Ceil(pgLevels) bits)
  /** fragmented_superpage support */
  val fragmented_superpage = Bool()
  /** homogeneous for both pma and pmp  */
  val homogeneous = Bool()
  val gpa = Flow(UInt(vaddrBits bits))
  val gpa_is_pte = Bool()
}

/** IO between TLB and PTW; master is the TLB.
  * (rocket-chip also routes the custom CSRs through here; they only feed
  * clock-gating, which this port does not implement.)
  */
class TLBPTWIO(implicit p: Parameters) extends CoreBundle()(p) with IMasterSlave {
  val req = Stream(new ValidPTWReq)
  val resp = Flow(new PTWResp)
  val ptbr = new PTBR()
  val hgatp = new PTBR()
  val vsatp = new PTBR()
  val status = new MStatus()
  val hstatus = new HStatus()
  val gstatus = new MStatus()
  val pmp = Vec.fill(nPMPs)(new PMP)

  override def asMaster(): Unit = {
    master(req)
    slave(resp)
    in(ptbr, hgatp, vsatp, status, hstatus, gstatus, pmp)
  }
}

/** PTW performance statistics */
class PTWPerfEvents extends Bundle {
  val l2miss = Bool()
  val l2hit = Bool()
  val pte_miss = Bool()
  val pte_hit = Bool()
}

/** Datapath IO between PTW and Core; master is the core. */
class DatapathPTWIO(implicit p: Parameters) extends CoreBundle()(p) with IMasterSlave {
  val ptbr = new PTBR()
  val hgatp = new PTBR()
  val vsatp = new PTBR()
  val sfence = Flow(new SFenceReq)
  val status = new MStatus()
  val hstatus = new HStatus()
  val gstatus = new MStatus()
  val pmp = Vec.fill(nPMPs)(new PMP)
  val perf = new PTWPerfEvents()
  /** enable clock generated by ptw */
  val clock_enabled = Bool()

  override def asMaster(): Unit = {
    out(ptbr, hgatp, vsatp, status, hstatus, gstatus, pmp)
    master(sfence)
    in(perf, clock_enabled)
  }
}

/** PTE template for transmission (RV-priv 4.3.1 layout, packed with ChiselLayout) */
class PTE(implicit p: Parameters) extends CoreBundle()(p) {
  val reserved_for_future = UInt(10 bits)
  val ppn = UInt(44 bits)
  val reserved_for_software = UInt(2 bits)
  /** dirty bit */
  val d = Bool()
  /** access bit */
  val a = Bool()
  /** global mapping */
  val g = Bool()
  /** user mode accessible */
  val u = Bool()
  /** whether the page is executable */
  val x = Bool()
  /** whether the page is writable */
  val w = Bool()
  /** whether the page is readable */
  val r = Bool()
  /** valid bit */
  val v = Bool()
  /** return true if find a pointer to next level page table */
  def table(dummy: Int = 0): Bool = v && !r && !w && !x && !d && !a && !u && reserved_for_future === 0
  /** return true if find a leaf PTE */
  def leaf(dummy: Int = 0): Bool = v && (r || (x && !w)) && a
  /** user read */
  def ur(dummy: Int = 0): Bool = sr() && u
  /** user write*/
  def uw(dummy: Int = 0): Bool = sw() && u
  /** user execute */
  def ux(dummy: Int = 0): Bool = sx() && u
  /** supervisor read */
  def sr(dummy: Int = 0): Bool = leaf() && r
  /** supervisor write */
  def sw(dummy: Int = 0): Bool = leaf() && w && d
  /** supervisor execute */
  def sx(dummy: Int = 0): Bool = leaf() && x
  /** full permission: writable and executable in user mode */
  def isFullPerm(dummy: Int = 0): Bool = uw() && ux()
}

/** L2TLB PTE template */
class L2TLBEntry(val nSets: Int)(implicit p: Parameters) extends CoreBundle()(p) {
  def idxBitsL2 = log2Ceil(nSets)
  def tagBitsL2 = maxSVAddrBits - pgIdxBits - idxBitsL2 + (if (usingHypervisor) 1 else 0)
  val tag = UInt(tagBitsL2 bits)
  val ppn = UInt(ppnBits bits)
  /** dirty bit */
  val d = Bool()
  /** access bit */
  val a = Bool()
  /** user mode accessible */
  val u = Bool()
  /** whether the page is executable */
  val x = Bool()
  /** whether the page is writable */
  val w = Bool()
  /** whether the page is readable */
  val r = Bool()
}

/** PTW contains L2TLB, and performs page table walk for high level TLB, and
  * cache queries from L1 TLBs(I$, D$, RoCC). See rocket-chip PTW.scala for the
  * full description of the structure and state machine.
  */
class PTW(n: Int)(implicit p: Parameters) extends CoreModule()(p) {
  val io = new Bundle {
    /** to n TLB */
    val requestor = Vec.fill(n)(slave(new TLBPTWIO))
    /** to HellaCache */
    val mem = master(new HellaCacheIO)
    /** to Core */
    val dpath = slave(new DatapathPTWIO)
  }

  def s_ready              = U(0, 3 bits)
  def s_req                = U(1, 3 bits)
  def s_wait1              = U(2, 3 bits)
  def s_dummy1             = U(3, 3 bits)
  def s_wait2              = U(4, 3 bits)
  def s_wait3              = U(5, 3 bits)
  def s_dummy2             = U(6, 3 bits)
  def s_fragment_superpage = U(7, 3 bits)
  val state = Reg(UInt(3 bits)) init s_ready
  val l2_refill_wire = Bool()
  /** Arbiter to arbite request from n TLB */
  val arb = new Arbiter(HardType(new ValidPTWReq), n)
  // use TLB req as arbitor's input
  (arb.io.in zip io.requestor.map(_.req)).foreach { case (a, r) => a << r }
  // receive req only when s_ready and not in refill
  arb.io.out.ready := (state === s_ready) && !l2_refill_wire

  val resp_valid = Vec.fill(io.requestor.size)(Reg(Bool()))
  resp_valid.foreach(_ := False)
  private def respond(): Unit = if (n == 1) resp_valid(0) := True else resp_valid(r_req_dest) := True

  val clock_en = state =/= s_ready || l2_refill_wire || arb.io.out.valid || io.dpath.sfence.valid
  io.dpath.clock_enabled := Bool(usingVM) && clock_en

  val invalidated = Reg(Bool())
  /** current PTE level: 0 <= count <= pgLevel-1 */
  val count = Reg(UInt(log2Ceil(pgLevels) bits))
  val resp_ae_ptw = Reg(Bool())
  val resp_ae_final = Reg(Bool())
  val resp_pf = Reg(Bool())
  val resp_gf = Reg(Bool())
  val resp_hr = Reg(Bool())
  val resp_hw = Reg(Bool())
  val resp_hx = Reg(Bool())
  val resp_fragmented_superpage = Reg(Bool())

  /** tlb request */
  val r_req = Reg(new PTWReq)
  /** current selected way in arbitor */
  val r_req_dest = Reg(UInt(log2Ceil(n) bits))
  // to respond to L1TLB : l2_hit
  // to construct mem.req.addr
  val r_pte = Reg(new PTE)
  val r_hgatp = Reg(new PTBR)
  // 2-stage pageLevel
  val aux_count = Reg(UInt(log2Ceil(pgLevels) bits))
  /** pte for 2-stage translation */
  val aux_pte = Reg(new PTE)
  val gpa_pgoff = Reg(UInt(pgIdxBits bits)) // only valid in resp_gf case
  val stage2 = Reg(Bool())
  val stage2_final = Reg(Bool())

  val satp = Mux(arb.io.out.payload.bits.vstage1, io.dpath.vsatp, io.dpath.ptbr)
  val cw = log2Ceil(pgLevels)
  val r_hgatp_initial_count = (U(pgLevels - minPgLevels, cw bits) - r_hgatp.additionalPgLevels.resize(cw))
  /** 2-stage translation both enable */
  val do_both_stages = r_req.vstage1 && r_req.stage2
  val max_count = Mux(count > aux_count, count, aux_count)
  val vpn = Mux(r_req.vstage1 && stage2, aux_pte.ppn, r_req.addr.resize(aux_pte.ppn.getWidth))

  val mem_resp_valid = RegNext(io.mem.resp.valid)
  val mem_resp_data = RegNext(io.mem.resp.payload.data)
  if (io.mem.uncached_resp != null) {
    val resp = io.mem.uncached_resp
    assert(!(resp.valid && io.mem.resp.valid))
    resp.ready := True
    when(resp.valid) {
      mem_resp_valid := True
      mem_resp_data := resp.payload.data
    }
  }
  // construct pte from mem.resp
  val (pte, invalid_paddr, invalid_gpa) = {
    val tmp = ChiselLayout.fromUInt(new PTE(), mem_resp_data)
    val res = CombInit(tmp)
    res.ppn := Mux(do_both_stages && !stage2, tmp.ppn((vpnBits min tmp.ppn.getWidth) - 1 downto 0).resize(44), tmp.ppn((ppnBits min tmp.ppn.getWidth) - 1 downto 0).resize(44))
    when(tmp.r || tmp.w || tmp.x) {
      // for superpage mappings, make sure PPN LSBs are zero
      for (i <- 0 until pgLevels - 1)
        when(count <= i && tmp.ppn((pgLevels - 1 - i) * pgLevelBits - 1 downto (pgLevels - 2 - i) * pgLevelBits) =/= 0) { res.v := False }
    }
    (res,
      !(do_both_stages && !stage2) && ((tmp.ppn >> ppnBits) =/= 0),
      do_both_stages && !stage2 && checkInvalidHypervisorGPA(r_hgatp, tmp.ppn))
  }
  // find non-leaf PTE, need traverse
  val traverse = pte.table() && !invalid_paddr && !invalid_gpa && count < (pgLevels - 1)
  /** address send to mem for enquerry */
  val pte_addr: UInt = if (!usingVM) U(0, 1 bits) else {
    val vpn_idxs = (0 until pgLevels).map { i =>
      val width = pgLevelBits + (if (i <= pgLevels - minPgLevels) hypervisorExtraAddrBits else 0)
      (vpn >> (pgLevels - i - 1) * pgLevelBits).resize(width)
    }
    val mw = hypervisorExtraAddrBits + pgLevelBits
    val mask = Mux(stage2 && count === r_hgatp_initial_count, U((1 << (hypervisorExtraAddrBits + pgLevelBits)) - 1, mw bits), U((1 << pgLevelBits) - 1, mw bits))
    val vpn_idx = vpn_idxs.map(_.resize(mw)).read(count) & mask
    val raw_pte_addr = ((r_pte.ppn << pgLevelBits) | vpn_idx.resized) << log2Ceil(xLen / 8)
    val size = if (usingHypervisor) vaddrBits else paddrBits
    //use r_pte.ppn as page table base address
    //use vpn slice as offset
    raw_pte_addr((size min raw_pte_addr.getWidth) - 1 downto 0)
  }
  /** stage2_pte_cache input addr */
  val stage2_pte_cache_addr: UInt = if (!usingHypervisor) U(0, 1 bits) else {
    val vpn_idxs = (0 until pgLevels - 1).map { i =>
      (r_req.addr >> (pgLevels - i - 1) * pgLevelBits)(pgLevelBits - 1 downto 0)
    }
    val vpn_idx = vpn_idxs.read(aux_count)
    val raw_s2_pte_cache_addr = Cat(aux_pte.ppn, vpn_idx).asUInt << log2Ceil(xLen / 8)
    raw_s2_pte_cache_addr((vaddrBits min raw_s2_pte_cache_addr.getWidth) - 1 downto 0)
  }

  def makeFragmentedSuperpagePPN(ppn: UInt): Seq[UInt] = {
    (pgLevels - 1 until 0 by -1).map(i => Cat(ppn >> (pgLevelBits * i), r_req.addr(((pgLevelBits * i) min vpnBits) - 1 downto 0).resize(pgLevelBits * i)).asUInt)
  }

  /** PTECache caches non-leaf PTE (rocket's nPTECacheEntries; 0 for BOOM) */
  def makePTECache(s2: Boolean): (Bool, UInt) = if (coreParams.nPTECacheEntries == 0) {
    (False, U(0, 1 bits))
  } else {
    val plru = new PseudoLRU(coreParams.nPTECacheEntries)
    val valid = Reg(UInt(coreParams.nPTECacheEntries bits)) init 0
    val tags = Reg(Vec.fill(coreParams.nPTECacheEntries)(UInt((if (usingHypervisor) 1 + vaddrBits else paddrBits) bits)))
    // not include full pte, only ppn
    val data = Reg(Vec.fill(coreParams.nPTECacheEntries)(UInt((if (usingHypervisor && s2) vpnBits else ppnBits) bits)))
    val can_hit =
      if (s2) count === r_hgatp_initial_count && aux_count < (pgLevels - 1) && r_req.vstage1 && stage2 && !stage2_final
      else count < (pgLevels - 1) && Mux(r_req.vstage1, stage2, !r_req.stage2)
    val can_refill =
      if (s2) do_both_stages && !stage2 && !stage2_final
      else can_hit
    val tag =
      if (s2) Cat(True, stage2_pte_cache_addr.resize(vaddrBits)).asUInt
      else Cat(r_req.vstage1, pte_addr.resize(if (usingHypervisor) vaddrBits else paddrBits)).asUInt

    val hits = tags.map(_ === tag.resized).asUInt & valid
    val hit = hits.orR && can_hit
    // refill with mem response
    when(mem_resp_valid && traverse && can_refill && !hits.orR && !invalidated) {
      val r = Mux(valid.andR, plru.way, PriorityEncoder(~valid))
      valid := valid | UIntToOH(r, coreParams.nPTECacheEntries)
      tags(r) := tag.resized
      data(r) := pte.ppn.resized
      plru.access(r)
    }
    // replace
    when(hit && state === s_req) { plru.access(OHToUInt(hits)) }
    when(io.dpath.sfence.valid && (!io.dpath.sfence.payload.rs1 || Bool(usingHypervisor) && io.dpath.sfence.payload.hg)) { valid := 0 }

    (hit, Mux1H(hits, data))
  }
  // generate pte_cache
  val (pte_cache_hit, pte_cache_data) = makePTECache(false)
  // generate pte_cache with 2-stage translation
  val (stage2_pte_cache_hit, stage2_pte_cache_data) = makePTECache(true)
  // pte_cache hit or 2-stage pte_cache hit
  val pte_hit = RegNext(False)
  io.dpath.perf.pte_miss := False
  io.dpath.perf.pte_hit := pte_hit && (state === s_req) && !io.dpath.perf.l2hit
  // l2_refill happens when find the leaf pte
  val l2_refill = RegNext(False)
  l2_refill_wire := l2_refill
  io.dpath.perf.l2miss := False
  io.dpath.perf.l2hit := False
  // l2tlb
  val (l2_hit, l2_error, l2_pte) = if (coreParams.nL2TLBEntries == 0) (False, False, new PTE().getZero) else {
    val code = new ParityCode
    require(isPow2(coreParams.nL2TLBEntries))
    require(isPow2(coreParams.nL2TLBWays))
    require(coreParams.nL2TLBEntries >= coreParams.nL2TLBWays)
    val nL2TLBSets = coreParams.nL2TLBEntries / coreParams.nL2TLBWays
    require(isPow2(nL2TLBSets))
    val idxBits = log2Ceil(nL2TLBSets)
    val nWays = coreParams.nL2TLBWays

    val l2_plru = new SetAssocLRU(nL2TLBSets, nWays, "plru")

    val entryW = (new L2TLBEntry(nL2TLBSets)).getBitsWidth
    val wordW = code.width(entryW)
    val ram = Mem(Bits(nWays * wordW bits), nL2TLBSets)

    val g = Reg(Vec.fill(nWays)(UInt(nL2TLBSets bits)))
    val valid = Vec.fill(nWays)(Reg(UInt(nL2TLBSets bits)) init 0)
    // use r_req to construct tag
    val split = Cat(r_req.vstage1, r_req.addr(maxSVAddrBits - pgIdxBits - 1 downto 0)).asUInt
    val r_tag = split >> idxBits
    val r_idx = split(idxBits - 1 downto 0)
    /** the valid vec for the selected set(including n ways) */
    val r_valid_vec = valid.map(_(r_idx)).asUInt
    val r_valid_vec_q = Reg(UInt(nWays bits))
    val r_l2_plru_way = Reg(UInt(log2Ceil(nWays max 1) bits))
    r_valid_vec_q := r_valid_vec
    // replacement way
    r_l2_plru_way := (if (nWays > 1) l2_plru.way(r_idx) else U(0, 0 bits))
    // refill with r_pte(leaf pte)
    val wmask = if (nWays > 1) Mux(r_valid_vec_q.andR, UIntToOH(r_l2_plru_way, nWays), PriorityEncoderOH(~r_valid_vec_q)) else U(1, 1 bits)
    val entry = new L2TLBEntry(nL2TLBSets)
    entry.ppn := r_pte.ppn.resized
    entry.d := r_pte.d
    entry.a := r_pte.a
    entry.u := r_pte.u
    entry.x := r_pte.x
    entry.w := r_pte.w
    entry.r := r_pte.r
    entry.tag := r_tag.resized
    val l2_write = l2_refill && !invalidated
    ram.write(r_idx, Cat(List.fill(nWays)(code.encode(entry.asBits.asUInt)): _*), l2_write, wmask.asBits)
    when(l2_write) {
      // if all the way are valid, use plru to select one way to be replaced,
      // otherwise use PriorityEncoderOH to select one
      val mask = UIntToOH(r_idx, nL2TLBSets)
      for (way <- 0 until nWays) {
        when(wmask(way)) {
          valid(way) := valid(way) | mask
          g(way) := Mux(r_pte.g, g(way) | mask, g(way) & ~mask)
        }
      }
    }
    // sfence happens
    when(io.dpath.sfence.valid) {
      val hg = Bool(usingHypervisor) && io.dpath.sfence.payload.hg
      for (way <- 0 until nWays) {
        valid(way) :=
          Mux(!hg && io.dpath.sfence.payload.rs1, valid(way) & ~UIntToOH(io.dpath.sfence.payload.addr(idxBits + pgIdxBits - 1 downto pgIdxBits), nL2TLBSets),
            Mux(!hg && io.dpath.sfence.payload.rs2, valid(way) & g(way),
              U(0, nL2TLBSets bits)))
      }
    }

    val s0_valid = !l2_refill && arb.io.out.fire
    val s0_suitable = arb.io.out.payload.bits.vstage1 === arb.io.out.payload.bits.stage2 && !arb.io.out.payload.bits.need_gpa
    val s1_valid = RegNext(s0_valid && s0_suitable && arb.io.out.payload.valid)
    val s2_valid = RegNext(s1_valid)
    // read from tlb idx
    val s1_rdata_flat = ram.readSyncChisel(arb.io.out.payload.bits.addr(idxBits - 1 downto 0), s0_valid)
    val s1_rdata = (0 until nWays).map(w => s1_rdata_flat(w * wordW, wordW bits).asUInt)
    val s2_rdata = s1_rdata.map(s1_rdway => code.decode(RegNextWhen(s1_rdway, s1_valid)))
    val s2_valid_vec = RegNextWhen(r_valid_vec, s1_valid)
    val s2_g_vec = RegNextWhen(Vec(g.map(_(r_idx))), s1_valid)
    val s2_error = (0 until nWays).map(way => s2_valid_vec(way) && s2_rdata(way).error).orR
    when(s2_valid && s2_error) { valid.foreach { _ := 0 } }
    // decode
    val s2_entry_vec = s2_rdata.map { d => val e = new L2TLBEntry(nL2TLBSets); e.assignFromBits(d.uncorrected.asBits); e }
    val s2_hit_vec = (0 until nWays).map(way => s2_valid_vec(way) && (r_tag.resize(s2_entry_vec(way).tag.getWidth) === s2_entry_vec(way).tag))
    val s2_hit = s2_valid && s2_hit_vec.orR
    io.dpath.perf.l2miss := s2_valid && !(s2_hit_vec.orR)
    io.dpath.perf.l2hit := s2_hit
    when(s2_hit) {
      l2_plru.access(r_idx, OHToUInt(s2_hit_vec))
      assert((PopCount(s2_hit_vec) === 1) || s2_error, "L2 TLB multi-hit")
    }

    val s2_pte = new PTE
    val s2_hit_entry = Mux1H(s2_hit_vec, s2_entry_vec)
    s2_pte.ppn := s2_hit_entry.ppn.resized
    s2_pte.d := s2_hit_entry.d
    s2_pte.a := s2_hit_entry.a
    s2_pte.g := Mux1H(s2_hit_vec, s2_g_vec)
    s2_pte.u := s2_hit_entry.u
    s2_pte.x := s2_hit_entry.x
    s2_pte.w := s2_hit_entry.w
    s2_pte.r := s2_hit_entry.r
    s2_pte.v := True
    s2_pte.reserved_for_future := 0
    s2_pte.reserved_for_software := 0

    (s2_hit, s2_error, s2_pte)
  }

  // if SFENCE occurs during walk, don't refill PTE cache or L2 TLB until next walk
  invalidated := io.dpath.sfence.valid || (invalidated && state =/= s_ready)
  // mem request
  io.mem.keep_clock_enabled := False

  io.mem.req.valid := state === s_req || state === s_dummy1
  io.mem.req.payload.phys := True
  io.mem.req.payload.cmd := M_XRD
  io.mem.req.payload.size := log2Ceil(xLen / 8)
  io.mem.req.payload.signed := False
  io.mem.req.payload.addr := pte_addr.resized
  if (io.mem.req.payload.idx != null) io.mem.req.payload.idx := pte_addr.resized
  io.mem.req.payload.dprv := PRV.S // PTW accesses are S-mode by definition
  io.mem.req.payload.dv := do_both_stages && !stage2
  io.mem.req.payload.tag.assignDontCare()
  io.mem.req.payload.no_resp := False
  io.mem.req.payload.no_alloc.assignDontCare()
  io.mem.req.payload.no_xcpt.assignDontCare()
  io.mem.req.payload.data.assignDontCare()
  io.mem.req.payload.mask.assignDontCare()

  io.mem.s1_kill := l2_hit || (state =/= s_wait1) || resp_gf
  io.mem.s1_data.assignDontCare()
  io.mem.s2_kill := False

  val pageGranularityPMPs = pmpGranularity >= (1 << pgIdxBits)
  require(!usingHypervisor || pageGranularityPMPs, s"hypervisor requires pmpGranularity >= ${1 << pgIdxBits}")

  val pmaPgLevelHomogeneous = (0 until pgLevels) map { i =>
    val pgSize = BigInt(1) << (pgIdxBits + ((pgLevels - 1 - i) * pgLevelBits))
    if (pageGranularityPMPs && i == pgLevels - 1) {
      require(TLBPageLookup.homogeneous(p.system.managers, pgSize), s"All memory regions must be $pgSize-byte aligned")
      True
    } else {
      TLBPageLookup.homogeneousAt(p.system.managers, xLen, cacheBlockBytes, pgSize, xLen / 8)((r_pte.ppn << pgIdxBits).resize(paddrBits))
    }
  }
  val pmaHomogeneous = pmaPgLevelHomogeneous.read(count)
  val pmpHomogeneous = new PMPHomogeneityChecker(io.dpath.pmp).apply((r_pte.ppn << pgIdxBits).resize(paddrBits), count)
  val homogeneous = pmaHomogeneous && pmpHomogeneous
  // response to tlb
  for (i <- 0 until io.requestor.size) {
    io.requestor(i).resp.valid := resp_valid(i)
    io.requestor(i).resp.payload.ae_ptw := resp_ae_ptw
    io.requestor(i).resp.payload.ae_final := resp_ae_final
    io.requestor(i).resp.payload.pf := resp_pf
    io.requestor(i).resp.payload.gf := resp_gf
    io.requestor(i).resp.payload.hr := resp_hr
    io.requestor(i).resp.payload.hw := resp_hw
    io.requestor(i).resp.payload.hx := resp_hx
    io.requestor(i).resp.payload.pte := r_pte
    io.requestor(i).resp.payload.level := max_count
    io.requestor(i).resp.payload.homogeneous := homogeneous || Bool(pageGranularityPMPs)
    io.requestor(i).resp.payload.fragmented_superpage := resp_fragmented_superpage && Bool(pageGranularityPMPs)
    io.requestor(i).resp.payload.gpa.valid := r_req.need_gpa
    io.requestor(i).resp.payload.gpa.payload :=
      Mux(
        r_req.vstage1,
        Cat(
          Mux(
            stage2,
            Mux(!stage2_final || aux_count === (pgLevels - 1), aux_pte.ppn, makeFragmentedSuperpagePPN(aux_pte.ppn).map(_.resize(44)).read(aux_count)),
            r_pte.ppn),
          gpa_pgoff).asUInt.resize(vaddrBits),
        r_req.addr.resize(vaddrBits))
    io.requestor(i).resp.payload.gpa_is_pte := !stage2_final
    io.requestor(i).ptbr := io.dpath.ptbr
    io.requestor(i).hgatp := io.dpath.hgatp
    io.requestor(i).vsatp := io.dpath.vsatp
    io.requestor(i).status := io.dpath.status
    io.requestor(i).hstatus := io.dpath.hstatus
    io.requestor(i).gstatus := io.dpath.gstatus
    io.requestor(i).pmp := io.dpath.pmp
  }

  // control state machine
  val next_state = CombInit(state)
  state := next_state
  val do_switch = CombInit(False)

  switch(state) {
    is(s_ready) {
      when(arb.io.out.fire) {
        val satp_initial_count = U(pgLevels - minPgLevels, cw bits) - satp.additionalPgLevels.resize(cw)
        val vsatp_initial_count = U(pgLevels - minPgLevels, cw bits) - io.dpath.vsatp.additionalPgLevels.resize(cw)
        val hgatp_initial_count = U(pgLevels - minPgLevels, cw bits) - io.dpath.hgatp.additionalPgLevels.resize(cw)
        val aux_ppn = Mux(arb.io.out.payload.bits.vstage1, io.dpath.vsatp.ppn, arb.io.out.payload.bits.addr.resize(io.dpath.vsatp.ppn.getWidth))

        r_req := arb.io.out.payload.bits
        r_req_dest := arb.io.chosen
        next_state := Mux(arb.io.out.payload.valid, s_req, s_ready)
        stage2 := arb.io.out.payload.bits.stage2
        stage2_final := arb.io.out.payload.bits.stage2 && !arb.io.out.payload.bits.vstage1
        count := Mux(arb.io.out.payload.bits.stage2, hgatp_initial_count, satp_initial_count)
        aux_count := Mux(arb.io.out.payload.bits.vstage1, vsatp_initial_count, U(0, cw bits))
        aux_pte.ppn := aux_ppn.resized
        aux_pte.reserved_for_future := 0
        resp_ae_ptw := False
        resp_ae_final := False
        resp_pf := False
        resp_gf := checkInvalidHypervisorGPA(io.dpath.hgatp, aux_ppn) && arb.io.out.payload.bits.stage2
        resp_hr := True
        resp_hw := True
        resp_hx := True
        resp_fragmented_superpage := False
        r_hgatp := io.dpath.hgatp

        assert(!arb.io.out.payload.bits.need_gpa || arb.io.out.payload.bits.stage2)
      }
    }
    is(s_req) {
      when(stage2 && count === r_hgatp_initial_count) {
        gpa_pgoff := Mux(aux_count === (pgLevels - 1), (r_req.addr << log2Ceil(xLen / 8)).resize(pgIdxBits), stage2_pte_cache_addr.resize(pgIdxBits))
      }
      // pte_cache hit
      when(stage2_pte_cache_hit) {
        aux_count := aux_count + 1
        aux_pte.ppn := stage2_pte_cache_data.resized
        aux_pte.reserved_for_future := 0
        pte_hit := True
      }.elsewhen(pte_cache_hit) {
        count := count + 1
        pte_hit := True
      }.otherwise {
        next_state := Mux(io.mem.req.ready, s_wait1, s_req)
      }
      when(resp_gf) {
        next_state := s_ready
        respond()
      }
    }
    is(s_wait1) {
      // This Mux is for the l2_error case; the l2_hit && !l2_error case is overriden below
      next_state := Mux(l2_hit, s_req, s_wait2)
    }
    is(s_wait2) {
      next_state := s_wait3
      io.dpath.perf.pte_miss := count < (pgLevels - 1)
      when(io.mem.s2_xcpt.ae.ld) {
        resp_ae_ptw := True
        next_state := s_ready
        respond()
      }
    }
    is(s_fragment_superpage) {
      next_state := s_ready
      respond()
      when(!homogeneous) {
        count := pgLevels - 1
        resp_fragmented_superpage := True
      }
      when(do_both_stages) {
        resp_fragmented_superpage := True
      }
    }
    default {}
  }

  val merged_pte = {
    val superpage_masks = (0 until pgLevels).map(i => U((BigInt(1) << pte.ppn.getWidth) - (BigInt(1) << (pgLevels - 1 - i) * pgLevelBits), pte.ppn.getWidth bits))
    val superpage_mask = superpage_masks.read(Mux(stage2_final, max_count, U(pgLevels - 1, cw bits)))
    val stage1_ppns = (0 until pgLevels - 1).map(i => Cat(pte.ppn(pte.ppn.getWidth - 1 downto (pgLevels - i - 1) * pgLevelBits), aux_pte.ppn((pgLevels - i - 1) * pgLevelBits - 1 downto 0)).asUInt) :+ pte.ppn
    val stage1_ppn = stage1_ppns.read(count)
    makePTE(stage1_ppn & superpage_mask, aux_pte)
  }

  r_pte := (
    // l2tlb hit->find a leaf PTE(l2_pte), respond to L1TLB
    Mux(l2_hit && !l2_error && !resp_gf, l2_pte,
    // S2 PTE cache hit -> proceed to the next level of walking, update the r_pte with hgatp
    Mux(state === s_req && stage2_pte_cache_hit, makeHypervisorRootPTE(r_hgatp, stage2_pte_cache_data, l2_pte),
    // pte cache hit->find a non-leaf PTE(pte_cache),continue to request mem
    Mux(state === s_req && pte_cache_hit, makePTE(pte_cache_data, l2_pte),
    // 2-stage translation
    Mux(do_switch, makeHypervisorRootPTE(r_hgatp, pte.ppn, r_pte),
    // when mem respond, store mem.resp.pte
    Mux(mem_resp_valid, Mux(!traverse && r_req.vstage1 && stage2, merged_pte, pte),
    // fragment_superpage
    Mux(state === s_fragment_superpage && !homogeneous && count =/= (pgLevels - 1), makePTE(makeFragmentedSuperpagePPN(r_pte.ppn).map(_.resize(44)).read(count), r_pte),
    // when tlb request come->request mem, use root address in satp(or vsatp,hgatp)
    Mux(arb.io.out.fire, Mux(arb.io.out.payload.bits.stage2, makeHypervisorRootPTE(io.dpath.hgatp, io.dpath.vsatp.ppn, r_pte), makePTE(satp.ppn, r_pte)),
    r_pte))))))))

  when(l2_hit && !l2_error && !resp_gf) {
    assert(state === s_req || state === s_wait1)
    next_state := s_ready
    respond()
    count := pgLevels - 1
  }
  when(mem_resp_valid) {
    assert(state === s_wait3)
    next_state := s_req
    when(do_both_stages && !stage2) {
      gpa_pgoff := {
        val vpn_idxs = (0 until pgLevels).map(i => (vpn >> ((pgLevels - i - 1) * pgLevelBits)).resize(vpnBits))
        val vpn_idx = vpn_idxs.read(count + 1)
        (vpn_idx << log2Ceil(xLen / 8)).resize(pgIdxBits)
      }
    }

    when(traverse) {
      when(do_both_stages && !stage2) { do_switch := True }
      count := count + 1
    }.otherwise {
      val gf = (stage2 && !stage2_final && !pte.ur()) ||
        (Mux(count === (pgLevels - 1), pte.leaf(), pte.v) && pte.reserved_for_future === 0 && invalid_gpa)
      val ae = pte.v && invalid_paddr && !(invalid_gpa && ((count =/= (pgLevels - 1)) || pte.leaf()))
      val pf = pte.v && pte.reserved_for_future =/= 0
      val success = pte.v && !ae && !pf && !gf

      when(do_both_stages && !stage2_final && success) {
        when(stage2) {
          stage2 := False
          count := aux_count
        }.otherwise {
          stage2_final := True
          do_switch := True
        }
      }.otherwise {
        // find a leaf pte, start l2 refill
        l2_refill := success && count === (pgLevels - 1) && !r_req.need_gpa &&
          (!r_req.vstage1 && !r_req.stage2 ||
            do_both_stages && aux_count === (pgLevels - 1) && pte.isFullPerm())
        count := max_count

        when(success && Bool(pageGranularityPMPs) && !(count === (pgLevels - 1) && (!do_both_stages || aux_count === (pgLevels - 1)))) {
          next_state := s_fragment_superpage
        }.otherwise {
          next_state := s_ready
          respond()
        }

        resp_ae_ptw := ae && ((count < (pgLevels - 1) && pte.table()) || (do_both_stages && !stage2_final))
        resp_ae_final := ae && pte.leaf() && !(do_both_stages && !stage2_final)
        resp_pf := pf && !stage2
        resp_gf := gf || (pf && stage2)
        resp_hr := !stage2 || (!pf && !gf && pte.ur())
        resp_hw := !stage2 || (!pf && !gf && pte.uw())
        resp_hx := !stage2 || (!pf && !gf && pte.ux())
      }
    }
  }
  when(io.mem.s2_nack) {
    assert(state === s_wait2)
    next_state := s_req
  }

  when(do_switch) {
    aux_count := Mux(traverse, count + 1, count)
    count := r_hgatp_initial_count
    aux_pte := Mux(traverse, pte, {
      val s1_ppns = (0 until pgLevels - 1).map(i => Cat(pte.ppn(pte.ppn.getWidth - 1 downto (pgLevels - i - 1) * pgLevelBits), r_req.addr((((pgLevels - i - 1) * pgLevelBits) min vpnBits) - 1 downto 0).resize((pgLevels - i - 1) * pgLevelBits)).asUInt) :+ pte.ppn
      makePTE(s1_ppns.read(count), pte)
    })
    stage2 := True
  }

  /** Relace PTE.ppn with ppn */
  private def makePTE(ppn: UInt, default: PTE): PTE = {
    val pte = CombInit(default)
    pte.ppn := ppn.resized
    pte
  }
  /** use hgatp and vpn to construct a new ppn */
  private def makeHypervisorRootPTE(hgatp: PTBR, vpn: UInt, default: PTE): PTE = {
    val count = U(pgLevels - minPgLevels, cw bits) - hgatp.additionalPgLevels.resize(cw)
    val idxs = (0 to pgLevels - minPgLevels).map(i => (vpn >> (pgLevels - i) * pgLevelBits).resize(maxHypervisorExtraAddrBits))
    val lsbs = idxs.read(count)
    val pte = CombInit(default)
    pte.ppn := Cat(hgatp.ppn >> maxHypervisorExtraAddrBits, lsbs).asUInt.resized
    pte
  }
  /** use hgatp and vpn to check for gpa out of range */
  private def checkInvalidHypervisorGPA(hgatp: PTBR, vpn: UInt): Bool = {
    val count = U(pgLevels - minPgLevels, cw bits) - hgatp.additionalPgLevels.resize(cw)
    val idxs = (0 to pgLevels - minPgLevels).map(i => (vpn >> ((pgLevels - i) * pgLevelBits) + maxHypervisorExtraAddrBits).resize(vpn.getWidth))
    idxs.read(count) =/= 0
  }
}
