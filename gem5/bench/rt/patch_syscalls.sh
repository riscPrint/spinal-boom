#!/bin/sh
# Print riscv-tests' benchmarks/common/syscalls.c ($1) with two changes for the
# RTL harness (src/test/scala/boom/sim/BenchmarksSpec.scala):
#  1. syscall() returns at once instead of using HTIF (tohost = pointer, wait for
#     fromhost). The harness only understands tohost = pass/fail, and has no
#     console. printf output is dropped.
#  2. setStats(0) also stores the ROI counters to `bench_stats` (cycles,
#     instret), which the harness picks up from the D$ store stream.
set -eu
in="$1"
grep -q '^  tohost = (uintptr_t)magic_mem;$' "$in" || { echo "patch_syscalls: syscall() changed upstream" >&2; exit 1; }
grep -q '^void setStats(int enable)$' "$in" || { echo "patch_syscalls: setStats() changed upstream" >&2; exit 1; }
echo "// Generated by gem5/bench/rt/patch_syscalls.sh from $in. Do not edit."
sed -e 's|^  tohost = (uintptr_t)magic_mem;$|  return 0; /* no HTIF host in the RTL sim */|' \
    -e 's|^void setStats(int enable)$|static void setStats_rt(int enable)|' "$in"
cat <<'C'

volatile uint64_t bench_stats[2] __attribute__((aligned(8)));

void setStats(int enable)
{
  setStats_rt(enable);
  if (!enable) {
    bench_stats[0] = counters[0]; /* mcycle delta */
    bench_stats[1] = counters[1]; /* minstret delta */
  }
}
C
